def features(name):
    work, parent, out = paths(name); destination = out / 'features.pt'
    if destination.exists(): return
    data = torch.load(work / 'data/pheme_model_improvement/graphs.pt', weights_only=False, map_location='cpu')
    result = {}
    for split in ['train', 'validation', 'test']:
        rows = [s for t in data if t['split'] == split for s in t['snapshots'] if len(s['target'])]
        result[split] = dict(x=np.concatenate([s['x'][s['sample_nodes']] for s in rows]),
                             target=np.concatenate([s['target'] for s in rows]))
        assert result[split]['x'].shape[1] == 184
    torch.save(result, destination)
    write(out / 'feature_proof.json', dict(input_sha256=sha(work / 'data/pheme_model_improvement/graphs.pt'),
        features_sha256=sha(destination), feature_dimension=184, original_rows_and_duplicates_preserved=True,
        test_labels_not_used_for_training_or_selection=True))


def forecast_features(common, original, current):
    # Both forecasts are generated by heads that already integrate the final
    # neural micro state and8h history. Trees calibrate these scalar forecasts;
    # this is explicitly not the historical latent-PCA mixed-readout version.
    hour = common['cutoff']/86400*2*np.pi
    return np.c_[np.log1p(original), np.log1p(current), common['ics'], common['profile'],
        np.log1p(np.maximum(common['observed'], 0)), common['sequence'].reshape(len(original), -1),
        common['memory_mean'], np.log1p(common['memory_count']), np.sin(hour), np.cos(hour)].astype(np.float32)


def forecasts(name, seed):
    work, parent, out = paths(name); dest = out / f'seed_{seed}'; dest.mkdir(exist_ok=True)
    if (dest / 'forecast_inputs.pt').exists(): return
    policy = read(parent / 'micro_selection.json')['policy']; selected = read(parent / 'macro_selection.json')
    common = torch.load(work / 'results/neural/common.pt', weights_only=False, map_location='cpu')
    values = {model: {split: dict(original=[], current=[], action=[]) for split in ['train', 'validation']} for model in MODELS}
    for b in BACKBONES:
        folder = work / 'results/neural' / b / f'seed_{seed}'
        old = torch.load(folder / 'development_final.pt', weights_only=False, map_location='cpu')
        original_model, _ = load_model(folder / 'temporal_model.pt')
        new = None
        if policy != 'chain':
            new = torch.load(parent / b / f'seed_{seed}' / policy / 'development_states.pt', weights_only=False, map_location='cpu')
        for model, variant in zip(MODELS, ['spatial', 'temporal']):
            config = selected[variant]['config']
            count_folder = folder / variant if config == 'legacy' else parent / 'counts' / config / variant / b / f'seed_{seed}'
            for split in ['train', 'validation']:
                a = common[split]; state = old[split]['state'][variant]
                original = memory_predict(folder / variant, a, state, peak=False)
                if variant == 'temporal' and new is not None: state = new[split]['state']
                current = memory_predict(count_folder, a, state, peak=config != 'legacy')
                values[model][split]['original'].append(original)
                values[model][split]['current'].append(current)
                if split == 'validation':
                    if variant == 'spatial': p = old[split]['action']['logits'].softmax(-1).numpy()
                    elif policy == 'chain': p = neural.action_probability(original_model, old[split]['action'], 'temporal')
                    else:
                        with np.load(parent / b / f'seed_{seed}' / policy / 'validation.npz') as saved: p = saved['probability']
                    values[model][split]['action'].append(p.astype(float))
        del old, original_model, new; gc.collect()
    result = {}
    for model in MODELS:
        result[model] = {}
        for split in ['train', 'validation']:
            v = values[model][split]; original = np.mean(v['original'], axis=0); current = np.mean(v['current'], axis=0)
            result[model][split] = dict(original=original, current=current,
                x=forecast_features(common[split], original, current),
                **{k: common[split][k] for k in ['target', 'thread_id', 'window', 'cutoff', 'end']})
            if split == 'validation': result[model][split]['action_probability'] = sum(v['action'])/3
    torch.save(result, dest / 'forecast_inputs.pt')
    write(dest / 'forecast_input_proof.json', dict(complete=True, neural_policy=policy,
        input_sha256=sha(dest / 'forecast_inputs.pt'), neural_macro_configs=selected,
        tree_macro_inputs='Original and current neural count forecasts plus observed history/profile; no future target counts'))


if __name__ == '__main__':
    p = argparse.ArgumentParser(); p.add_argument('mode', choices=['features', 'forecasts'])
    p.add_argument('--dataset', choices=list(SPEC), required=True); p.add_argument('--seed', type=int, default=42)
    a = p.parse_args(); torch.set_num_threads(1); verify_plan()
    if a.mode == 'features': features(a.dataset)
    else: forecasts(a.dataset, a.seed)
